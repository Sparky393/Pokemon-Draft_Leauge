// Download these Showdown files from the same revision, then run:
// node scripts/import-champions-learnsets.mjs /path/to/learnsets.ts /path/to/moves.ts
// Sources: data/mods/champions/learnsets.ts and data/moves.ts in
// https://github.com/smogon/pokemon-showdown (MIT license).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import assert from "node:assert/strict";

const [learnsetsPath, movesPath] = process.argv.slice(2);
const source = readFileSync(learnsetsPath, "utf8");
const movesSource = readFileSync(movesPath, "utf8");
const names = new Map();
for (const match of movesSource.matchAll(/^\t(?:"([^"]+)"|(\w+)): \{\n([\s\S]*?)^\t\},/gm)) {
  const name = match[3].match(/^\t\tname: "([^"]+)",/m)?.[1];
  if (name) names.set(match[1] || match[2], name);
}
const learnsets = {};
for (const match of source.matchAll(/^\t(\w+): \{\n(?:\t\tinherit: true,\n)?\t\tlearnset: \{\n([\s\S]*?)\t\t\},\n\t\},/gm)) {
  learnsets[match[1]] = [...match[2].matchAll(/^\t\t\t(\w+):/gm)].map(([, id]) => {
    assert.ok(names.has(id), `Missing move name: ${id}`);
    return names.get(id);
  });
}
assert.ok(Object.keys(learnsets).length > 200, "Incomplete Champions dataset");
assert.ok(!learnsets.emolga.includes("Tailwind"));
const hash = createHash("sha256").update(source).digest("hex");
writeFileSync("src/main/resources/static/js/champions-learnsets.js",
  `/* Generated by scripts/import-champions-learnsets.mjs.\n * Source: https://github.com/smogon/pokemon-showdown/blob/master/data/mods/champions/learnsets.ts\n * Learnsets SHA-256: ${hash}\n *\n${readFileSync("docs/pokemon-showdown-LICENSE", "utf8").split("\n").map(line => ` * ${line}`).join("\n")}\n */\nconst CHAMPIONS_LEARNSETS = ${JSON.stringify(learnsets, null, 2)};\n`);
console.log(`Imported ${Object.keys(learnsets).length} Champions learnsets.`);
